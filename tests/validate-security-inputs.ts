import assert from "node:assert/strict";
import { patientRecordsQuerySchema, selectedTestsSchema, moneySchema, infertilityStatusSchema } from "../src/lib/securityInputs";
import { newPasswordSchema } from "../src/lib/passwordSchema";
import { generatePassword, validatePassword } from "../src/lib/passwordPolicy";
import { createInfertilityTestSchema } from "../src/app/(authenticated)/infertility/types/schemas";
for (const data of [{ page: "0" }, { page: "-1" }, { page: "1junk" }, { limit: "101" }, { limit: "1.5" }, { startDate: "bad" }, { search: "a".repeat(201) }]) assert.equal(patientRecordsQuerySchema.safeParse(data).success, false);
assert.deepEqual(patientRecordsQuerySchema.parse({}), { page: 1, limit: 15 });
assert.equal(patientRecordsQuerySchema.safeParse({ limit: "100", page: "2", startDate: "2026-10-29" }).success, true);
assert.equal(selectedTestsSchema.safeParse(["HB%", "HB%"]).success, false);
assert.equal(selectedTestsSchema.safeParse(["a".repeat(201)]).success, false);
assert.equal(moneySchema.safeParse(Infinity).success, false);
assert.equal(moneySchema.safeParse(-1).success, false);
assert.equal(infertilityStatusSchema.safeParse("arbitrary").success, false);
assert.equal(infertilityStatusSchema.safeParse("Follow-up").success, true);
assert.equal(newPasswordSchema.safeParse("password123").success, false);
for (let i = 0; i < 100; i++) assert.equal(validatePassword(generatePassword()).valid, true);
const valid = { infertilityPatientId: 1, subjectType: "PATIENT", selectedTests: ["HB%"], testCharge: 200, grandTotal: 200, paidAmount: 0, dueAmount: 200, orderedById: 1 };
assert.equal(createInfertilityTestSchema.safeParse(valid).success, true);
assert.equal(createInfertilityTestSchema.safeParse({ ...valid, discountValue: -1 }).success, false);
assert.equal(createInfertilityTestSchema.safeParse({ ...valid, infertilityPatientId: 1.5 }).success, false);
console.log("Security input validation passed");
